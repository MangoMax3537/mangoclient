  let current = 'de';

  function t(key, vars) {
    let str = STRINGS[current]?.[key] ?? STRINGS.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) str = str.replaceAll(`{${k}}`, v);
    }
    return str;
  }

  function setLanguage(lang) {
    current = STRINGS[lang] ? lang : 'en';
    document.documentElement.lang = current;
    applyStatic();
  }

  /** Re-translate everything marked up with data-i18n / data-i18n-ph. */
  function applyStatic(root = document) {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    // Rail/statusbar tooltips render from an attribute, not from text content.
    root.querySelectorAll('[data-tip]').forEach((el) => {
      el.dataset.tipText = t(el.dataset.tip);
    });
  }

  window.i18n = { t, setLanguage, applyStatic, get lang() { return current; } };
